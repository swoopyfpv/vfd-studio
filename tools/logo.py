SRC=sys.argv[1]; OUT=sys.argv[2]
im=np.array(Image.open(SRC).convert('L'))<128
# icon: 24x22 design units, sampled and made point-symmetric (the source is hand-drawn on a ~21 px grid)
x0,y0,x1,y1=267,130,781,593;nx,ny=24,22;ux=(x1-x0)/nx;uy=(y1-y0)/ny
v=np.array([[im[int(y0+j*uy):int(y0+(j+1)*uy),int(x0+i*ux):int(x0+(i+1)*ux)].mean() for i in range(nx)] for j in range(ny)])
units=((v+v[::-1,::-1])/2>.5)
# every feature sits on 2x2 units -> 3x3 px blocks (1.5 px per unit)
icon=np.zeros((33,36),np.uint8)
for j in range(0,22,2):
  for i in range(0,24,2):
    if units[j:j+2,i:i+2].mean()>=.5: icon[j//2*3:j//2*3+3,i//2*3:i//2*3+3]=1
# arms = 4-connected components
lab=np.zeros_like(icon);n=0
for y in range(33):
  for x in range(36):
    if icon[y,x] and not lab[y,x]:
      n+=1;st=[(y,x)];lab[y,x]=n
      while st:
        a,b=st.pop()
        for c,d in((a+1,b),(a-1,b),(a,b+1),(a,b-1)):
          if 0<=c<33 and 0<=d<36 and icon[c,d] and not lab[c,d]:lab[c,d]=n;st.append((c,d))
assert n==4,n
def rows(s):return np.array([[1 if ch=='#' else 0 for ch in r] for r in s.strip('\n').split('\n')],np.uint8)
