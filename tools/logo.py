def xbm(a):
  h,w=a.shape;st=(w+7)>>3;o=[]
  for y in range(h):
    for bx in range(st):
      v=0
      for k in range(8):
        xx=bx*8+k
        if xx<w and a[y,xx]:v|=1<<k
      o.append(v)
  return o
