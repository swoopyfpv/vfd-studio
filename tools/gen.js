// Generates firmware headers from the built studio HTML: fonts.h, demos.h, studio.h
const fs=require('fs'),zlib=require('zlib'),path=require('path');
const [html,outDir]=process.argv.slice(2);
const src=fs.readFileSync(html,'utf8');
const script=src.slice(src.indexOf('<script>')+8,src.lastIndexOf('</script>'));
// evaluate the pure parts (fonts + demos) in a sandbox
const core=script.slice(0,script.indexOf('/* ============================================================\n   APP'));
const ctx={};new Function('ctx','btoa','atob',core+';ctx.F57=F57;ctx.F35SRC=F35SRC;ctx.demos=demos;ctx.FONTS=FONTS;ctx.LAND=LAND;ctx.SIN256=SIN256;')(ctx,s=>Buffer.from(s,'binary').toString('base64'),s=>Buffer.from(s,'base64').toString('binary'));
// fonts.h
let f='// generated by tools/gen.js from the studio — do not edit\n#pragma once\n#include <stdint.h>\nnamespace vfd {\n';
f+='static const uint8_t F57[64][5] = {'+Array.from({length:64},(_,i)=>'{'+ctx.F57.slice(i*5,i*5+5).join(',')+'}').join(',')+'};\n';
const small=[],ok=[];
for(let c=32;c<128;c++){const g=ctx.FONTS.small.g[String.fromCharCode(c)];small.push(g||[0,0,0]);ok.push(g?1:0);}
f+='static const uint8_t F35[96][3] = {'+small.map(g=>'{'+g.join(',')+'}').join(',')+'};\n';
f+='static const uint8_t F35_OK[96] = {'+ok.join(',')+'};\n';
f+='static const uint8_t F35_DEG[3] = {'+ctx.FONTS.small.g['°'].join(',')+'};\n';
f+='static const uint8_t F35_MID[3] = {'+ctx.FONTS.small.g['·'].join(',')+'};\n';
f+='static const uint8_t F57_DEG[5] = {'+ctx.FONTS.medium.g['°'].join(',')+'};\n';
f+='static const uint8_t F57_MID[5] = {'+ctx.FONTS.medium.g['·'].join(',')+'};\n';
f+='static const int16_t SIN256[256] = {'+ctx.SIN256.join(',')+'};\n';
f+='static const uint8_t LAND[4096] = {'+Array.from(ctx.LAND).join(',')+'};\n}\n';
fs.writeFileSync(path.join(outDir,'fonts.h'),f);
// demos.h
// only the clock ships in the firmware (first boot + fallback); the other demos come from Studio / Builder templates
const demos=ctx.demos().filter(p=>p.id==='neon-clock');
let d='// generated by tools/gen.js — demo projects written to flash on first boot\n#pragma once\n';
d+='static const char* const DEMO_JSON[] = {\n'+demos.map(p=>'  R"VFDJSON('+JSON.stringify(p)+')VFDJSON"').join(',\n')+'\n};\n';
d+='static const int DEMO_COUNT = '+demos.length+';\n';
fs.writeFileSync(path.join(outDir,'demos.h'),d);
// studio.h (gzipped page)
const gz=zlib.gzipSync(Buffer.from(src,'utf8'),{level:9});
let h='// generated by tools/gen.js — gzipped VFD Studio web app\n#pragma once\n#include <stdint.h>\n';
h+=`static const uint32_t STUDIO_GZ_LEN = ${gz.length};\nstatic const uint8_t STUDIO_GZ[] = {\n`;
for(let i=0;i<gz.length;i+=32)h+=Array.from(gz.slice(i,i+32)).join(',')+',\n';
h+='};\n';
fs.writeFileSync(path.join(outDir,'studio.h'),h);
console.log('fonts ok · demos',demos.length,'· studio gz',(gz.length/1024).toFixed(1),'KB');
